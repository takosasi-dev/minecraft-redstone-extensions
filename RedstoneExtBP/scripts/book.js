function showSection(player, index) {
  const section = SECTIONS[index];
  const form = new ActionFormData()
    .title(section.title)
    .body(section.body.join("\n"))
    .button("§7< 目次に戻る§r");

  form.show(player).then((res) => {
    if (res.canceled) return;
    openGuide(player);
  });
}

function showIndex(player) {
  const form = new ActionFormData()
    .title("レッドストーン拡張アドオン")
    .body("読みたい章を選ぶ。");
  for (const section of SECTIONS) form.button(section.title);

  form.show(player).then((res) => {
    if (res.canceled || res.selection === undefined) return;
    showSection(player, res.selection);
  });
}

/** フォームは読み取り専用コンテキストから開けないので次 tick に回す。 */
export function openGuide(player) {
  system.run(() => {
    try {
      showIndex(player);
    } catch (e) {
      console.warn(`[wr] guide book failed: ${e}`);
    }
  });
}

export const guideBookComponent = {
  onUse(e) {
    if (e.source) openGuide(e.source);
  },
};
